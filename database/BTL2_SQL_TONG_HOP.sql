CREATE OR ALTER PROCEDURE dbo.usp_FIX_Test
    @Ten NVARCHAR(200),@Sql NVARCHAR(MAX),@MaLoiMongDoi INT=0
AS
BEGIN
    SET NOCOUNT ON;
    IF @@TRANCOUNT<>0 THROW 51990,N'Chạy test ngoài giao dịch đang mở.',1;
    DECLARE @Loi INT=0,@ThongBao NVARCHAR(4000);
    BEGIN TRY
        BEGIN TRANSACTION;
        EXEC(@Sql);
    END TRY
    BEGIN CATCH
        SELECT @Loi=ERROR_NUMBER(),@ThongBao=ERROR_MESSAGE();
    END CATCH;
    IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
    IF @Loi<>@MaLoiMongDoi
    BEGIN
        SET @ThongBao=CONCAT(N'FAIL ',@Ten,N': kỳ vọng ',@MaLoiMongDoi,N', thực tế ',@Loi,N'. ',@ThongBao);
        THROW 51991,@ThongBao,1;
