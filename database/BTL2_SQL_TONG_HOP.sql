   Khoá phiếu rồi khoá mặt hàng theo thứ tự mã trước kiểm tồn/chốt. */
CREATE OR ALTER PROCEDURE dbo.usp_N2_GhiSoPhieuKho
    @MaPhieuKho VARCHAR(30),@NguoiDuyet VARCHAR(30),@ThoiDiem DATETIME2(0)
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT ON;
    IF @@TRANCOUNT<>0 THROW 51429,N'Demo ghi sổ chạy ngoài giao dịch đang mở.',1;
    BEGIN TRY
        BEGIN TRANSACTION;
        DECLARE @Loai VARCHAR(30),@Lap VARCHAR(30),@TrangThai VARCHAR(30);
        SELECT @Loai=LoaiPhieu,@Lap=NguoiLap,@TrangThai=TrangThaiPhieu FROM dbo.PHIEU_KHO WITH(UPDLOCK,HOLDLOCK) WHERE MaPhieuKho=@MaPhieuKho;
        IF @Loai IS NULL OR @TrangThai<>'Nhap' OR @ThoiDiem IS NULL THROW 51430,N'Không có phiếu nháp hoặc thiếu thời điểm.',1;
        IF @Loai='XuatBan' THROW 51431,N'XuatBan chỉ chốt trong giao dịch thanh toán.',1;
        DECLARE @Hang VARCHAR(30),@LockValue VARCHAR(30);
        DECLARE c CURSOR LOCAL FAST_FORWARD FOR SELECT MaHangHoa FROM dbo.CHI_TIET_PHIEU_KHO WHERE MaPhieuKho=@MaPhieuKho ORDER BY MaHangHoa;
        OPEN c; FETCH NEXT FROM c INTO @Hang;
        WHILE @@FETCH_STATUS=0
        BEGIN
            SELECT @LockValue=MaHangHoa FROM dbo.HANG_HOA WITH(UPDLOCK,HOLDLOCK) WHERE MaHangHoa=@Hang;
            FETCH NEXT FROM c INTO @Hang;
        END;
        CLOSE c; DEALLOCATE c;
        IF @Loai='KiemKe'
            UPDATE c SET TonTruocGhiSo=x.Ton,BienDongSoLuong=c.SoLuongThucTe-x.Ton
            FROM dbo.CHI_TIET_PHIEU_KHO c CROSS APPLY
            (SELECT CONVERT(DECIMAL(18,6),COALESCE(SUM(q.BienDongSoLuong),0)) AS Ton FROM dbo.CHI_TIET_PHIEU_KHO q JOIN dbo.PHIEU_KHO p ON p.MaPhieuKho=q.MaPhieuKho
             WHERE q.MaHangHoa=c.MaHangHoa AND p.TrangThaiPhieu='DaGhiSo') x WHERE c.MaPhieuKho=@MaPhieuKho;
        UPDATE dbo.PHIEU_KHO SET NguoiDuyet=@NguoiDuyet,ThoiDiemDuyet=@ThoiDiem,ThoiDiemGhiSo=@ThoiDiem,TrangThaiPhieu='DaGhiSo' WHERE MaPhieuKho=@MaPhieuKho;
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF CURSOR_STATUS('local','c')>=0 CLOSE c;
        IF CURSOR_STATUS('local','c')>=-1 DEALLOCATE c;
        IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH;
END;
GO
